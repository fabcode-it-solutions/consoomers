import { db } from "@/db/db";
import { eq } from "drizzle-orm";
import bcrypt from "bcryptjs";
import { users } from "@/db/schema/users";

export async function findUserByEmail({
  email,
  passwordToken,
}: {
  email?: string;
  passwordToken?: string;
}) {
  try {
    if (email) {
      const [user] = await db
        .select()
        .from(users)
        .where(eq(users.email, email))
        .limit(1);
      return user ?? null;
    }

    if (passwordToken) {
      const [user] = await db
        .select()
        .from(users)
        .where(eq(users.resetPasswordToken, passwordToken))
        .limit(1);
      return user ?? null;
    }

    return null;
  } catch (error) {
    console.error("Error finding user by email:", error);
    return null;
  }
}

export async function createUser({
  email,
  password,
  firstName,
  lastName,
  username,
  phoneNumber,
  role = "brand",
}: {
  email: string;
  password: string;
  firstName?: string;
  lastName?: string;
  username?: string;
  phoneNumber?: string;
  role?: "brand" | "tester" | "admin";
}) {
  try {
    const passwordHash = await bcrypt.hash(password, 12);

    const [user] = await db
      .insert(users)
      .values({
        email,
        passwordHash,
        firstName: firstName || "",
        lastName: lastName || "",
        username: username || "",
        phoneNumber: phoneNumber || null,
        role,
        emailVerified: false,
        createdAt: new Date(),
        updatedAt: new Date(),
        // notificationId is auto-generated by database (defaultRandom())
      })
      .returning();

    if (user) user.passwordHash = "";
    return user;
  } catch (err) {
    console.error("Error creating user:", err);
    return null;
  }
}

export async function getUserById(id: string) {
  try {
    const [user] = await db
      .select()
      .from(users)
      .where(eq(users.id, id))
      .limit(1);
    if (user) user.passwordHash = "";
    return user ?? null;
  } catch (error) {
    console.error("Error getting user by ID:", error);
    return null;
  }
}

export const findUserByResetToken = async (token: string) => {
  const [user] = await db
    .select()
    .from(users)
    .where(eq(users.resetPasswordToken, token))
    .limit(1);
  return user || null;
};

export async function updateUser(
  identifier: { id?: string; email?: string; passwordToken?: string },
  data: Partial<typeof users.$inferInsert>
) {
  try {
    if (!identifier.id && !identifier.email && !identifier.passwordToken) {
      throw new Error(
        "Either 'id' or 'email' or 'passwordToken' must be provided"
      );
    }

    const whereClause = identifier.id
      ? eq(users.id, identifier.id)
      : identifier.email
      ? eq(users.email, identifier.email)
      : eq(users.resetPasswordToken, identifier.passwordToken!);

    const [user] = await db
      .update(users)
      .set({ ...data, updatedAt: new Date() })
      .where(whereClause)
      .returning();

    if (user) user.passwordHash = "";
    return user;
  } catch (error) {
    console.error("Error updating user:", error);
    throw new Error("Failed to update user");
  }
}

export async function createOrUpdateUser({
  email,
  name,
}: {
  email: string;
  name?: string | null;
}) {
  try {
    const [existing] = await db
      .select()
      .from(users)
      .where(eq(users.email, email))
      .limit(1);

    if (existing) {
      if (existing.passwordHash) existing.passwordHash = "";
      return existing;
    }

    const [newUser] = await db
      .insert(users)
      .values({
        email,
        passwordHash: "",
        firstName: name || "",
        lastName: "",
        username: name?.replaceAll(" ", "") || "",
        role: "tester",
        emailVerified: true,
        createdAt: new Date(),
        updatedAt: new Date(),
        // notificationId is auto-generated by database (defaultRandom())
      })
      .returning();

    if (newUser) newUser.passwordHash = "";
    return newUser;
  } catch (error) {
    console.error("Error creating or updating user:", error);
    throw new Error("Failed to create or update user");
  }
}